    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        try {

        String textoDia = txtPrecioDia.getText();
        String textoNoche = txtPrecioNoche.getText();
        String textoFinSemana = txtPrecioFindeSemana.getText();

        textoDia = textoDia.replace("Q", "").trim();
        textoNoche = textoNoche.replace("Q", "").trim();
        textoFinSemana = textoFinSemana.replace("Q", "").trim();

        double dia = Double.parseDouble(textoDia);
        double noche = Double.parseDouble(textoNoche);
        double finSemana = Double.parseDouble(textoFinSemana);

        boolean modificado = tarifa.modificarTarifas(
                dia, noche, finSemana);

        if (modificado) {

            cambiosPendientes = true;

            JOptionPane.showMessageDialog(this,
                    "Tarifas modificadas en memoria.");

            mostrarTarifas();

            txtPrecioDia.setEditable(false);
            txtPrecioNoche.setEditable(false);
            txtPrecioFindeSemana.setEditable(false);

            btnEditar.setEnabled(true);
            btnModificar.setEnabled(false);
            btnGuardar.setEnabled(true);

        } else {

            JOptionPane.showMessageDialog(this,
                    "Los precios deben ser válidos y mayores que cero.");
        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "Ingrese precios numéricos válidos.");
    } // TODO add your handling code here:
    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        boolean guardado = archivoTarifas.guardarTarifas(tarifa);

    if (guardado) {

        cambiosPendientes = false;

        JOptionPane.showMessageDialog(this,
                "Tarifas guardadas correctamente en CSV.");

        btnGuardar.setEnabled(false);

    } else {

        JOptionPane.showMessageDialog(this,
                "Error al guardar las tarifas.");
    }// TODO add your handling code here:
    }//GEN-LAST:event_btnGuardarActionPerformed


