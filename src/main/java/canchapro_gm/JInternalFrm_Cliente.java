    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
    String busqueda = txtBuscar.getText().trim();
    String tipo = cmbTipodeBusqueda.getSelectedItem().toString();

    if (busqueda.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Ingrese un dato para buscar");
        return;
    }

    DefaultTableModel modelo =
            (DefaultTableModel) tbClientes.getModel();

    modelo.setRowCount(0);

    if (tipo.equalsIgnoreCase("Buscar por Código")) {

        Cliente cliente=gestorClientes.buscarClientePorCodigo(busqueda);

        if (cliente != null) {
            String estado;

            if (cliente.estaActivo()) {
                estado = "Activo";
            } else {
                estado = "Inactivo";
            }

            Object[] fila = { 
                cliente.getCodigo(),
                cliente.getNombre(),
                cliente.getTelefono(),
                cliente.getCorreo(),
                cliente.getFechaRegistro(),
                estado
            };

            modelo.addRow(fila);

        } else {
            JOptionPane.showMessageDialog(this,
                    "No se encontró el cliente con el codigo");
        }

    } else if (tipo.equalsIgnoreCase("Buscar por Nombre")) {

        Cliente[] encontrados =gestorClientes.buscarClientesPorNombre(busqueda);

        for (int i = 0; i < encontrados.length; i++) {

            Cliente clienteActual = encontrados[i];
            String estado;
             if (clienteActual.estaActivo()) {
            estado = "Activo";
        } else {
            estado = "Inactivo";
        }

            Object[] fila = {
                clienteActual.getCodigo(),
                clienteActual.getNombre(),
                clienteActual.getTelefono(),
                clienteActual.getCorreo(),
                clienteActual.getFechaRegistro(), 
                estado
            };

            modelo.addRow(fila);
        }

        if (encontrados.length == 0) {
            JOptionPane.showMessageDialog(this,
                    "No se encontraron cliente con el nombre ingresado");
        }
    }
    tbClientes.clearSelection();;
     btnModificar.setEnabled(false);
    btnDesactivar.setEnabled(false);
    btnReactivar.setEnabled(false);
    btnRegistrar.setEnabled(true);
    
    }//GEN-LAST:event_btnBuscarActionPerformed

