    public void mostrarServicios(){
       DefaultTableModel modelo = new DefaultTableModel();

    modelo.addColumn("Código");
    modelo.addColumn("Nombre");
    modelo.addColumn("Precio");
    modelo.addColumn("Estado");

    ServicioAdicional[] servicios =gestorServicios.obtenerServicios();

    for (int i = 0; i < servicios.length; i++) {

        ServicioAdicional servicio = servicios[i];

        if (servicio != null) {

            String estado;

            if (servicio.estaActivo()) {
                estado = "Activo";
            } else {
                estado = "Inactivo";
            }

            Object[] fila = {
                servicio.getCodigo(),
                servicio.getNombre(),
                servicio.getPrecio(),
                estado
            };

            modelo.addRow(fila);
        }
    }

    tbServicios.setModel(modelo);
        
    }

