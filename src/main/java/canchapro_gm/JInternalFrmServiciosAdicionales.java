    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
     String codigo = txtCodigo.getText();
    String nombre = txtNombreServicio.getText().trim();
    String textoPrecio = txtPrecio.getText().trim();

    if (codigo.isEmpty() || nombre.isEmpty()|| textoPrecio.isEmpty()) {
    JOptionPane.showMessageDialog(this,"Complete todos los campos.");
        return;
    }

    double precio;

    try {precio = Double.parseDouble(textoPrecio);
    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "Ingrese un precio válido.");
        return;
    }

    if (!Double.isFinite(precio) || precio < 0) {

        JOptionPane.showMessageDialog(this,
                "El precio no es válido.");
        return;
    }

    ServicioAdicional servicio =new ServicioAdicional(codigo, nombre, precio);

    boolean registrado =gestorServicios.agregarServicio(servicio);

    if (registrado) {

        JOptionPane.showMessageDialog(this,"Servicio ha registrado correctamente.");

        cambiosPendientes = true;

        mostrarServicios();

        txtCodigo.setText(gestorServicios.generarCodigo());
        txtNombreServicio.setText("");
        txtPrecio.setText("");
        cmboxEstado.setSelectedItem("Activo");

    } else {

        JOptionPane.showMessageDialog(this,"No se pudo registrar el servicio.");
    }
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnGuardarCambiosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarCambiosActionPerformed
  if (cambiosPendientes == false) {

        JOptionPane.showMessageDialog(this,
                "No hay cambios pendientes por guardar.");
        return;
    }

    boolean guardado = gestorServicios.guardarServicios();

    if (guardado) {

        JOptionPane.showMessageDialog(this,
                "Servicios guardados correctamente.");

        cambiosPendientes = false;

    } else {

        JOptionPane.showMessageDialog(this,
                "Error al guardar los servicios.");
    }        // TODO add your handling code here:
    }//GEN-LAST:event_btnGuardarCambiosActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
    String codigo = txtCodigo.getText();
    String nombre = txtNombreServicio.getText().trim();
    String textoPrecio = txtPrecio.getText().trim();

    if (codigo.isEmpty() || nombre.isEmpty()|| textoPrecio.isEmpty()) {

        JOptionPane.showMessageDialog(this, "Complete todos los campos.");
        return;
    }

    double precio;

    try {
        precio = Double.parseDouble(textoPrecio);

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "Ingrese un precio válido.");
        return;
    }

    if (!Double.isFinite(precio) || precio < 0) {

        JOptionPane.showMessageDialog(this,
                "El precio no es válido.");
        return;
    }

    boolean modificado = gestorServicios.modificarServicio(codigo, nombre, precio);

    if (modificado) {

        JOptionPane.showMessageDialog(this,"Servicio modificado correctamente.");

        cambiosPendientes = true;

        mostrarServicios();

        btnModificar.setEnabled(false);

    } else {

        JOptionPane.showMessageDialog(this,
                "No se pudo modificar el servicio.");
    }       
    }//GEN-LAST:event_btnModificarActionPerformed

