    private void mostrarPagos() {

    DefaultTableModel modelo =(DefaultTableModel) tbPagos.getModel();

    // Limpiar la tabla
    modelo.setRowCount(0);

    // Verificar que exista una reserva seleccionada
    if (reservaSeleccionada == null) {
        return;
    }

    // Obtener los pagos de la reserva
    Pago[] pagos = gestorPagos.obtenerPagosPorReserva(
            reservaSeleccionada.getCodigo()
    );

    // Recorrer el arreglo de pagos
    for (int i = 0; i < pagos.length; i++) {

        Pago pago = pagos[i];

        Object[] fila = {
            pago.getCodigo(),
            pago.getFecha(),
            pago.getHora(),
            pago.getMonto(),
            pago.getMetodoPago(),
            pago.getObservacion()
        };

        modelo.addRow(fila);
    }
}

