    private void btnBuscarReservaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarReservaActionPerformed
reservaSeleccionada = null;
btnRegistrarAbono.setEnabled(false);
mostrarPagos();
String codigo = txtCodigoReserva.getText().trim();

if (codigo.isEmpty()) {

    JOptionPane.showMessageDialog(this,"Ingrese el código de la reserva");
    return;
}

Reserva reserva = gestorReservas.buscarReserva(codigo);

if (reserva == null) {

    JOptionPane.showMessageDialog(this,"No se encontró la reserva");

    btnRegistrarAbono.setEnabled(false);
    return;
}
reservaSeleccionada=reserva;
mostrarPagos();
// Mostrar información
jblCliente.setText(reserva.getCodigoCliente());
jblCancha.setText(reserva.getCodigoCancha());
jblFechaReserva.setText(reserva.getFecha().toString());
jblEstadoReserva.setText(reserva.getEstado().toString());

jblTotal.setText("Q" + reserva.getTotal());
jblTotalPagado.setText("Q" + reserva.getTotalPagado());
jblSaldo.setText("Q" + reserva.calcularSaldo());


if (reserva.calcularSaldo() > 0 && reserva.getEstado() != EstadoReserva.CANCELADA
        && reserva.getEstado() != EstadoReserva.FINALIZADA) {

    btnRegistrarAbono.setEnabled(true);

} else {

    btnRegistrarAbono.setEnabled(false);
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnBuscarReservaActionPerformed

    private void btnRegistrarAbonoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarAbonoActionPerformed
     String codigoReserva = txtCodigoReserva.getText().trim();

// Verificar que exista la reserva
Reserva reserva = gestorReservas.buscarReserva(codigoReserva);

if (reserva == null) {
    JOptionPane.showMessageDialog(this,
            "Primero debe buscar una reserva");
    return;
}


if (txtMonto.getText().trim().isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "Ingrese el monto del abono");
    return;
}

double monto;

try {
    monto = Double.parseDouble(txtMonto.getText().trim());

} catch (NumberFormatException e) {

    JOptionPane.showMessageDialog(this,"Ingrese un monto válido");
    return;
}

// Verificar el monto
if (!Double.isFinite(monto) || monto <= 0) {
    JOptionPane.showMessageDialog(this, "El monto debe ser mayor que cero");
    return;
}

// Verificar el saldo disponible
if (monto > reserva.calcularSaldo()) {
    JOptionPane.showMessageDialog(this, "El abono no puede superar el saldo pendiente");
    return;
}

// Obtener el método de pago
if (cmboxMetodoPago.getSelectedItem() == null) {
    JOptionPane.showMessageDialog(this,
            "Seleccione un método de pago");
    return;
}
String metodoSeleccionado =cmboxMetodoPago.getSelectedItem().toString();

MetodoPago metodo =MetodoPago.valueOf(metodoSeleccionado);

// Obtener observación
String observacion = txtObservacion.getText().trim();

// Registrar el pago
Pago pago = gestorPagos.registrarPago(
        codigoReserva,
        monto,
        metodo,
        observacion
);

// Comprobar el resultado
if (pago != null) {JOptionPane.showMessageDialog(this,
            "Abono registrado correctamente\n"
            + "Código de pago: " + pago.getCodigo());

    // Actualizar información
    jblTotalPagado.setText("Q" + reserva.getTotalPagado());
    jblSaldo.setText("Q" + reserva.calcularSaldo());

    // Limpiar campos del abono
    txtMonto.setText("");
    txtObservacion.setText("");

    // Deshabilitar si ya se pagó todo
    if (reserva.calcularSaldo() <= 0) {
        btnRegistrarAbono.setEnabled(false);
    }

} else {

    JOptionPane.showMessageDialog(this,
            "No se pudo registrar el abono");
}   // TODO add your handling code here:
    }//GEN-LAST:event_btnRegistrarAbonoActionPerformed

